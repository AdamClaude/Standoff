let lang: Lang = (store.get('standoff.lang') as Lang) || (navigator.language.startsWith('ar') ? 'ar' : 'en');
const listeners = new Set<() => void>();

function apply() {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
}
apply();

export function setLang(l: Lang) {
  lang = l;
  store.set('standoff.lang', l);
  apply();
  listeners.forEach(f => f());
}

export function getLang() { return lang; }

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  const s = (lang === 'ar' ? ar[key] : undefined) ?? en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}

export function useLang(): Lang {
  return useSyncExternalStore(cb => { listeners.add(cb); return () => listeners.delete(cb); }, () => lang);
}

